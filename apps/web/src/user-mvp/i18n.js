export function createTranslator(language = 'en') {
  const selected = SUPPORTED_LANGUAGES.includes(language) ? language : 'en';

  return (key, params = {}) => {
    let value = messages[selected][key] ?? messages.en[key] ?? params.fallback ?? key;
    for (const [name, replacement] of Object.entries(params)) {
      if (name !== 'fallback') value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  };
}

export function translateStatus(status, t) {
  return t(`status.${status}`, { fallback: status });
}

export function translateValidationError(error, t) {
  return t(`validation.${error.code}`, { fallback: error.message ?? error.code });
}

export function translateWarning(warning, t, nameFor) {
  return t(`warning.${warning.code}`, {
    fallback: warning.code,
    source: nameFor(warning.sourceId),
  });
}

export function translateRecommendation(recommendation, t, nameFor) {
  return t(`recommendation.${recommendation.type}`, {
    fallback: recommendation.type,
    entity: nameFor(recommendation.entityId),
    improvementMinutes: recommendation.improvementMinutes,
  });
}
